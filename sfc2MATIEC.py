class SFCConverter:
    def __init__(self, sfc_file):
        self.sfc_file     = sfc_file
        self.steps        = []
        self.transitions  = []
        self.variables    = []
        self.initial_step = None
        self.st_lines     = []

    # ------------------------------------------------------------------ #
    #  STEP 1  Parse                                                      #
    # ------------------------------------------------------------------ #
    def parse(self):
        print("\n  [STEP 1] Parsing : {}".format(self.sfc_file))
        try:
            with open(self.sfc_file, 'r') as f:
                src = f.read()
            ns = {}
            exec(compile(src, self.sfc_file, 'exec'), {}, ns)
            self.steps        = ns.get('steps',        [])
            self.transitions  = ns.get('transitions',  [])
            self.variables    = ns.get('variables',    [])
            self.initial_step = ns.get('initial_step', None)
            print(
                "         Steps       : {}"
                "         Transitions : {}"
                "         Variables   : {}"
                "         Initial step: {}".format(len(self.steps),len(self.transitions),len(self.variables),self.initial_step)
            )
            return True
        except Exception as e:
            print("         Parse ERROR : {}".format(e))
            return False

    def _infer_variable_type(self, variable_dict, var_name=""):
        """
        Infer variable type based on initialization value or variable name patterns.
        If variable has explicit 'type', use it.
        Otherwise, check 'init' value:
        - If TRUE/FALSE -> BOOL
        - If number -> INT or REAL
        - If variable name suggests BOOL (Q, enabled, etc.) -> BOOL
        - Otherwise -> INT (default for numeric variables)
        """
        if isinstance(variable_dict, dict):
            # Explicit type provided
            if 'type' in variable_dict and variable_dict['type']:
                return variable_dict['type']
            
            # Try to infer from init value
            if 'init' in variable_dict:
                init_val = variable_dict['init']
                # Check if it's a boolean
                if isinstance(init_val, bool):
                    return 'BOOL'
                # Check if it's a string representation of TRUE/FALSE
                if isinstance(init_val, str) and init_val.upper() in ('TRUE', 'FALSE'):
                    return 'BOOL'
                # Check if it's a float
                if isinstance(init_val, float):
                    return 'REAL'
                # Check if it's an integer (but not boolean, since bool is subclass of int)
                if isinstance(init_val, int) and not isinstance(init_val, bool):
                    return 'INT'
                # Try to parse as number
                try:
                    if '.' in str(init_val):
                        float(init_val)
                        return 'REAL'
                    else:
                        int(init_val)
                        return 'INT'
                except (ValueError, TypeError):
                    pass
            
            # Try to infer from 'value' field (alternative naming)
            if 'value' in variable_dict:
                val = variable_dict['value']
                if isinstance(val, bool):
                    return 'BOOL'
                if isinstance(val, str) and val.upper() in ('TRUE', 'FALSE'):
                    return 'BOOL'
                if isinstance(val, float):
                    return 'REAL'
                if isinstance(val, int) and not isinstance(val, bool):
                    return 'INT'
                try:
                    if '.' in str(val):
                        float(val)
                        return 'REAL'
                    else:
                        int(val)
                        return 'INT'
                except (ValueError, TypeError):
                    pass
        
        # If it's a plain string variable, check naming patterns
        if var_name:
            var_name_lower = var_name.lower()
            # Common BOOL variable patterns
            if any(pattern in var_name_lower for pattern in ['q', 'enabled', 'active', 'flag', 'is_', 'has_', 'error', 'status']):
                return 'BOOL'
            # Common REAL variable patterns
            if any(pattern in var_name_lower for pattern in ['temperature', 'pressure', 'voltage', 'current', 'flow', 'speed', 'position', 'time', 'distance', 'weight', 'value', 'margin', 'log_']):
                return 'REAL'
        
        # Default to INT for numeric variables
        return 'INT'

    def _get_variable_init_value(self, variable_dict, var_type):
        """
        Get the initial value for a variable based on its type.
        """
        if isinstance(variable_dict, dict):
            # Explicit init value provided
            if 'init' in variable_dict:
                init_val = variable_dict['init']
                if var_type == 'BOOL':
                    if isinstance(init_val, bool):
                        return 'TRUE' if init_val else 'FALSE'
                    elif isinstance(init_val, str) and init_val.upper() in ('TRUE', 'FALSE'):
                        return init_val.upper()
                    else:
                        return 'FALSE'
                else:
                    return str(init_val)
            
            if 'value' in variable_dict:
                val = variable_dict['value']
                if var_type == 'BOOL':
                    if isinstance(val, bool):
                        return 'TRUE' if val else 'FALSE'
                    elif isinstance(val, str) and val.upper() in ('TRUE', 'FALSE'):
                        return val.upper()
                    else:
                        return 'FALSE'
                else:
                    return str(val)
        
        # Default init values based on type
        if var_type == 'BOOL':
            return 'FALSE'
        elif var_type in ('INT', 'DINT'):
            return '0'
        elif var_type == 'REAL':
            return '0.0'
        else:
            return '0'

    def _translate_guard(self, guard):
        expr = str(guard).strip() if guard is not None else ""
        if not expr:
            return "TRUE"

        # Convert Python-style guard expressions into MATIEC/IEC ST syntax.
        expr = expr.replace("&&", " AND ").replace("||", " OR ")
        expr = expr.replace("!=", "<>")
        expr = expr.replace("==", "=")
        expr = re.sub(r"\bnot\b", "NOT", expr, flags=re.IGNORECASE)
        expr = re.sub(r"\band\b", "AND", expr, flags=re.IGNORECASE)
        expr = re.sub(r"\bor\b", "OR", expr, flags=re.IGNORECASE)
        expr = re.sub(r"\btrue\b", "TRUE", expr, flags=re.IGNORECASE)
        expr = re.sub(r"\bfalse\b", "FALSE", expr, flags=re.IGNORECASE)
        return expr

    # ------------------------------------------------------------------ #
    #  STEP 2  Generate ST                                               #
    # ------------------------------------------------------------------ #
    def generate(self):
        print("\n  [STEP 2] Generating ST code ...", end="")
        L = self.st_lines
        L.clear()
        L.append("PROGRAM SFC_Program")
        L.append("(* Auto-generated by sfc_converter_batch.py *)")
        L.append("")
        L.append("VAR")
        for s in self.steps:
            L.append("  {}_active : BOOL := FALSE;".format(s['name']))
        
        for v in self.variables:
            if isinstance(v, dict):
                vname = v.get('name', str(v))
                # Infer type based on init value or name
                vtype = self._infer_variable_type(v, vname)
            else:
                vname = str(v)
                # For plain strings, infer type from variable name
                vtype = self._infer_variable_type(None, vname)
            
            # Get proper initial value for the inferred type
            init = self._get_variable_init_value(v, vtype)
            L.append("  {} : {} := {};".format(vname, vtype, init))
        
        L.append("END_VAR")
        L.append("")
        L.append("(* --- Initialise initial step --- *)")
        L.append("IF NOT {}_active THEN".format(self.initial_step))
        L.append("  {}_active := TRUE;".format(self.initial_step))
        L.append("END_IF;")
        L.append("")
        L.append("(* --- Transitions --- *)")
        for t in self.transitions:
            src   = t.get('src',   'UNKNOWN')
            tgt   = t.get('tgt',   'UNKNOWN')
            guard = self._translate_guard(t.get('guard', 'TRUE'))
            L.append("IF {}_active AND ({}) THEN".format(src, guard))
            L.append("  {}_active := FALSE;".format(src))
            L.append("  {}_active := TRUE;".format(tgt))
            L.append("END_IF;")
        L.append("")
        L.append("END_PROGRAM")
        print("         {} lines of ST generated.".format(len(L)))

    # ------------------------------------------------------------------ #
    #  STEP 3  Save .st                                                  #
    # ------------------------------------------------------------------ #
    def save(self, out_file):
        print("\n  [STEP 3] Saving : {}".format(out_file))
        return codegenutil.savefile(out_file, "\n".join(self.st_lines))

    # ------------------------------------------------------------------ #
    #  STEP 4  Compile with MATIEC (or fallback syntax check)            #
    # ------------------------------------------------------------------ #
    def compile(self, st_file):
        print("[STEP 4] MATIEC compilation ...{}".format(st_file))
        result = subprocess.run(["make", "-f", "compile_st.mk", f"SRC={st_file}"], capture_output=True, text=True)
        if result.returncode == 0:
            return True, "MATIEC compilation successful.", "MATIEC"
        else:
            err = result.stderr.strip() or result.stdout.strip()
             #ok, msg = self._syntax_check(st_file)
            return False, err, "MATIEC"

    # ------------------------------------------------------------------ #
    #  Built-in syntax checker                                           #
    # ------------------------------------------------------------------ #
    def _syntax_check(self, st_file):
        errors = []
        with open(st_file, 'r') as f:
            code = f.read()
        pairs = [
            ('PROGRAM',  'END_PROGRAM'),
            ('VAR',      'END_VAR'),
            ('IF',       'END_IF'),
            ('FOR',      'END_FOR'),
            ('WHILE',    'END_WHILE'),
            ('CASE',     'END_CASE'),
        ]
        for kw_open, kw_close in pairs:
            cnt_open  = len([l for l in code.split('\n')
                             if l.strip().startswith(kw_open)])
            cnt_close = code.count(kw_close)
            if cnt_open != cnt_close:
                errors.append("Mismatched {}/{} ({} open, {} close)"
                              .format(kw_open, kw_close, cnt_open, cnt_close))
        assign_lines = [l.strip() for l in code.split('\n')
                        if ':=' in l and not l.strip().startswith('(*')]
        for line in assign_lines:
            if not line.endswith(';'):
                errors.append("Missing semicolon: {}".format(line))
        if errors:
            return False, "\n".join(errors)
        return True, "Built-in syntax check PASSED."

    # ------------------------------------------------------------------ #
    #  Full pipeline  returns a result dict                             #
    # ------------------------------------------------------------------ #
    def run(self, out_file=None):
        result = {
            "sfc_file"   : self.sfc_file,
            "steps"      : 0,
            "transitions": 0,
            "variables"  : 0,
            "st_file"    : "",
            "compiler"   : "",
            "status"     : "",
            "message"    : "",
            "timestamp"  : datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        }

        parse_ok = self.parse()
        if not parse_ok:
            result.update(status="FAILED", message="Parse error", compiler="N/A")
            return result

        result["steps"]       = len(self.steps)
        result["transitions"] = len(self.transitions)
        result["variables"]   = len(self.variables)

        self.generate()

        if out_file is None:
            out_file     = os.path.splitext(self.sfc_file)[0] + ".st"
        result["st_file"] = out_file
        
        if not self.save(out_file):
            result.update(status="FAILED", message="Save error", compiler="N/A")
            return result

        ok, msg, compiler = self.compile(out_file)
        result["compiler"] = compiler
        result["status"]   = "SUCCESS" if ok else "FAILED"
        result["message"]  = msg

        # Console final banner per file
        #print("=" * 60)
        #print("  FILE     : {}".format(os.path.basename(self.sfc_file)))
        #print("  COMPILER : {}".format(compiler))
        #print("  RESULT   : --> {}".format(result["status"]))
        if not ok:
            print("  DETAILS  :\n{}".format(msg))
        #print("=" * 60)
        return result



#  TXT Report Generator                                                

def generate_txt_report(results, report_path):
    W = 65  # report width
    lines = []

    def rule(char="="):
        return char * W

    def center(text, char=" "):
        return text.center(W)

    def row(label, value):
        return "  {:<22} {}".format(label, value)

  
    lines.append(rule("="))
    lines.append(center("SFC  ->  MATIEC  Compilation Batch Report"))
    lines.append(center("Generated : {}".format(
        datetime.datetime.now().strftime("%Y-%m-%d  %H:%M:%S"))))
    lines.append(rule("="))
    lines.append("")

   
    for idx, r in enumerate(results, start=1):
        lines.append(rule("-"))
        lines.append("  FILE #{} of {}".format(idx, len(results)))
        lines.append(rule("-"))
        lines.append(row("SFC File    :", os.path.basename(r["sfc_file"])))
        lines.append(row("ST File     :", os.path.basename(r.get("st_file", "N/A"))))
        lines.append(row("Steps       :", r["steps"]))
        lines.append(row("Transitions :", r["transitions"]))
        lines.append(row("Variables   :", r["variables"]))
        lines.append(row("Compiler    :", r["compiler"]))
        lines.append(row("Status      :", "[ {} ]".format(r["status"])))
        lines.append(row("Timestamp   :", r["timestamp"]))
        if r["message"]:
            lines.append("")
            lines.append("  Message / Details:")
            for mline in r["message"].splitlines():
                lines.append("    " + mline)
        lines.append("")

   
    total     = len(results)
    successes = sum(1 for r in results if r["status"] == "SUCCESS")
    failures  = total - successes

    lines.append(rule("="))
    lines.append(center("BATCH  SUMMARY"))
    lines.append(rule("="))
    lines.append(row("Total Files :", total))
    lines.append(row("Succeeded   :", successes))
    lines.append(row("Failed      :", failures))
    lines.append("")
    lines.append(rule("-"))
    lines.append("  {:<5} {:<35} {:<15} {}".format(
        "#", "SFC File", "Compiler", "Status"))
    lines.append(rule("-"))
    for idx, r in enumerate(results, start=1):
        icon = "[OK]  " if r["status"] == "SUCCESS" else "[FAIL]"
        name = os.path.basename(r["sfc_file"])[:34]
        lines.append("  {:<5} {:<35} {:<15} {}".format(
            idx, name, r["compiler"], icon))
    lines.append(rule("="))
    lines.append("")

    
    with open(report_path, 'w', encoding='utf-8') as f:
        f.write("\n".join(lines))

    print("\n[REPORT] TXT report saved : {}".format(report_path))



