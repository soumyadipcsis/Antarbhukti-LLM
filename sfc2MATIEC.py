class SFCJSONConverter:
    """
    Converts SFC definitions from JSON format (containing sfc_baseline and 
    sfc_upgraded) into two ST files for separate compilation.
    """
    
    def __init__(self, json_file):
        self.json_file = json_file
        self.baseline_sfc = None
        self.upgraded_sfc = None
        self.baseline_st_lines = []
        self.upgraded_st_lines = []
    
    def parse(self):
        """Parse JSON file and extract baseline and upgraded SFC definitions."""
        import json
        print("\n  [STEP 1] Parsing JSON file: {}".format(self.json_file))
        try:
            with open(self.json_file, 'r') as f:
                data = json.load(f)
            
            self.baseline_sfc = data.get('sfc_baseline', {})
            self.upgraded_sfc = data.get('sfc_upgraded', {})
            
            print("    Baseline SFC:")
            print("      Steps       : {}".format(len(self.baseline_sfc.get('steps', []))))
            print("      Transitions : {}".format(len(self.baseline_sfc.get('transitions', []))))
            print("      Variables   : {}".format(len(self.baseline_sfc.get('variables', []))))
            
            print("    Upgraded SFC:")
            print("      Steps       : {}".format(len(self.upgraded_sfc.get('steps', []))))
            print("      Transitions : {}".format(len(self.upgraded_sfc.get('transitions', []))))
            print("      Variables   : {}".format(len(self.upgraded_sfc.get('variables', []))))
            
            return True
        except Exception as e:
            print("    Parse ERROR: {}".format(e))
            return False
    
    def _infer_variable_type(self, variable_dict, var_name=""):
        """
        Infer variable type based on initialization value or variable name patterns.
        If variable has explicit 'type', use it.
        Otherwise, check 'init' value:
        - If TRUE/FALSE -> BOOL
        - If number -> INT or REAL
        - If variable name suggests BOOL (Q, enabled, etc.) -> BOOL
        - Otherwise -> INT (default for numeric variables)
        """
        if isinstance(variable_dict, dict):
            # Explicit type provided
            if 'type' in variable_dict and variable_dict['type']:
                return variable_dict['type']
            
            # Try to infer from init value
            if 'init' in variable_dict:
                init_val = variable_dict['init']
                # Check if it's a boolean
                if isinstance(init_val, bool):
                    return 'BOOL'
                # Check if it's a string representation of TRUE/FALSE
                if isinstance(init_val, str) and init_val.upper() in ('TRUE', 'FALSE'):
                    return 'BOOL'
                # Check if it's a float
                if isinstance(init_val, float):
                    return 'REAL'
                # Check if it's an integer (but not boolean)
                if isinstance(init_val, int) and not isinstance(init_val, bool):
                    return 'INT'
                # Try to parse as number
                try:
                    if '.' in str(init_val):
                        float(init_val)
                        return 'REAL'
                    else:
                        int(init_val)
                        return 'INT'
                except (ValueError, TypeError):
                    pass
            
            # Try to infer from 'value' field (alternative naming)
            if 'value' in variable_dict:
                val = variable_dict['value']
                if isinstance(val, bool):
                    return 'BOOL'
                if isinstance(val, str) and val.upper() in ('TRUE', 'FALSE'):
                    return 'BOOL'
                if isinstance(val, float):
                    return 'REAL'
                if isinstance(val, int) and not isinstance(val, bool):
                    return 'INT'
                try:
                    if '.' in str(val):
                        float(val)
                        return 'REAL'
                    else:
                        int(val)
                        return 'INT'
                except (ValueError, TypeError):
                    pass
        
        # If it's a plain string variable, check naming patterns
        if var_name:
            var_name_lower = var_name.lower()
            # Common BOOL variable patterns
            if any(pattern in var_name_lower for pattern in ['q', 'enabled', 'active', 'flag', 'is_', 'has_', 'error', 'status']):
                return 'BOOL'
            # Common REAL variable patterns
            if any(pattern in var_name_lower for pattern in ['temperature', 'pressure', 'voltage', 'current', 'flow', 'speed', 'position', 'time', 'distance', 'weight', 'value', 'margin', 'log_']):
                return 'REAL'
        
        # Default to INT for numeric variables
        return 'INT'

    def _get_variable_init_value(self, variable_dict, var_type):
        """
        Get the initial value for a variable based on its type.
        """
        if isinstance(variable_dict, dict):
            # Explicit init value provided
            if 'init' in variable_dict:
                init_val = variable_dict['init']
                if var_type == 'BOOL':
                    if isinstance(init_val, bool):
                        return 'TRUE' if init_val else 'FALSE'
                    elif isinstance(init_val, str) and init_val.upper() in ('TRUE', 'FALSE'):
                        return init_val.upper()
                    else:
                        return 'FALSE'
                else:
                    return str(init_val)
            
            if 'value' in variable_dict:
                val = variable_dict['value']
                if var_type == 'BOOL':
                    if isinstance(val, bool):
                        return 'TRUE' if val else 'FALSE'
                    elif isinstance(val, str) and val.upper() in ('TRUE', 'FALSE'):
                        return val.upper()
                    else:
                        return 'FALSE'
                else:
                    return str(val)
        
        # Default init values based on type
        if var_type == 'BOOL':
            return 'FALSE'
        elif var_type in ('INT', 'DINT'):
            return '0'
        elif var_type == 'REAL':
            return '0.0'
        else:
            return '0'

    def _translate_guard(self, guard):
        """Translate guard expressions from Python-style to MATIEC/IEC ST syntax."""
        expr = str(guard).strip() if guard is not None else ""
        if not expr:
            return "TRUE"
        
        expr = expr.replace("&&", " AND ").replace("||", " OR ")
        expr = expr.replace("!=", "<>")
        expr = expr.replace("==", "=")
        expr = re.sub(r"\bnot\b", "NOT", expr, flags=re.IGNORECASE)
        expr = re.sub(r"\band\b", "AND", expr, flags=re.IGNORECASE)
        expr = re.sub(r"\bor\b", "OR", expr, flags=re.IGNORECASE)
        expr = re.sub(r"\btrue\b", "TRUE", expr, flags=re.IGNORECASE)
        expr = re.sub(r"\bfalse\b", "FALSE", expr, flags=re.IGNORECASE)
        return expr
    
    def _generate_st(self, sfc_data, output_lines):
        """
        Generate ST code from SFC data (baseline or upgraded).
        Appends to output_lines list.
        """
        L = output_lines
        steps = sfc_data.get('steps', [])
        transitions = sfc_data.get('transitions', [])
        variables = sfc_data.get('variables', [])
        initial_step = sfc_data.get('initial_step', None)
        
        L.append("PROGRAM SFC_Program")
        L.append("(* Auto-generated by SFCJSONConverter *)")
        L.append("")
        L.append("VAR")
        
        # Step flags
        for s in steps:
            step_name = s.get('name', 'UNKNOWN') if isinstance(s, dict) else str(s)
            L.append("  {}_active : BOOL := FALSE;".format(step_name))
        
        # User variables
        for v in variables:
            if isinstance(v, dict):
                vname = v.get('name', str(v))
                # Infer type based on init value or name
                vtype = self._infer_variable_type(v, vname)
            else:
                vname = str(v)
                # For plain strings, infer type from variable name
                vtype = self._infer_variable_type(None, vname)
            
            # Get proper initial value for the inferred type
            init = self._get_variable_init_value(v, vtype)
            L.append("  {} : {} := {};".format(vname, vtype, init))
        
        L.append("END_VAR")
        L.append("")
        
        # Initialize initial step
        L.append("(* --- Initialize initial step --- *)")
        L.append("IF NOT {}_active THEN".format(initial_step))
        L.append("  {}_active := TRUE;".format(initial_step))
        L.append("END_IF;")
        L.append("")
        
        # Step actions
        L.append("(* --- Step actions --- *)")
        for s in steps:
            if isinstance(s, dict):
                step_name = s.get('name', 'UNKNOWN')
                step_func = s.get('function', '').strip()
            else:
                step_name = str(s)
                step_func = ''
            
            if step_func:
                L.append("IF {}_active THEN".format(step_name))
                L.append("  {};".format(step_func))
                L.append("END_IF;")
        
        L.append("")
        
        # Transitions
        L.append("(* --- Transitions --- *)")
        for t in transitions:
            src = t.get('src', 'UNKNOWN')
            tgt = t.get('tgt', 'UNKNOWN')
            guard = self._translate_guard(t.get('guard', 'TRUE'))
            
            L.append("IF {}_active AND ({}) THEN".format(src, guard))
            L.append("  {}_active := FALSE;".format(src))
            L.append("  {}_active := TRUE;".format(tgt))
            L.append("END_IF;")
        
        L.append("")
        L.append("END_PROGRAM")
    
    def generate(self):
        """
        Generate ST code for both baseline and upgraded SFC definitions.
        """
        print("\n  [STEP 2] Generating ST code for both baseline and upgraded ...")
        
        self.baseline_st_lines.clear()
        self.upgraded_st_lines.clear()
        
        self._generate_st(self.baseline_sfc, self.baseline_st_lines)
        self._generate_st(self.upgraded_sfc, self.upgraded_st_lines)
        
        print("    Baseline ST : {} lines generated.".format(len(self.baseline_st_lines)))
        print("    Upgraded ST : {} lines generated.".format(len(self.upgraded_st_lines)))
    
    def save(self, baseline_out, upgraded_out):
        """
        Save both baseline and upgraded ST files.
        """
        print("\n  [STEP 3] Saving : {}...  ".format(baseline_out), end="")
        baseline_ok = codegenutil.savefile(baseline_out, "\n".join(self.baseline_st_lines))
        
        print("\n  [STEP 3] Saving : {}".format(upgraded_out))
        upgraded_ok = codegenutil.savefile(upgraded_out, "\n".join(self.upgraded_st_lines))
        
        return baseline_ok and upgraded_ok
    
    def compile(self, baseline_st_file, upgraded_st_file):
        """
        Compile both ST files using iec2iec (or MATIEC).
        Returns (baseline_ok, baseline_msg, upgraded_ok, upgraded_msg)
        """
        print("\n  [STEP 4] Compiling both ST files with iec2iec ...")
        
        def compile_file(st_file, label):
            """Compile a single ST file."""
            print("\n    Compiling {} : {}".format(label, st_file))
            result = subprocess.run(
                ["make", "-f", "compile_st.mk", "SRC={}".format(st_file)],
                capture_output=True,
                text=True,
                timeout=30
            )
            
            if result.returncode == 0:
                return True, "Compilation successful."
            else:
                err = result.stderr.strip() or result.stdout.strip()
                return False, err
        
        baseline_ok, baseline_msg = compile_file(baseline_st_file, "BASELINE")
        upgraded_ok, upgraded_msg = compile_file(upgraded_st_file, "UPGRADED")
        
        return baseline_ok, baseline_msg, upgraded_ok, upgraded_msg
    
    def run(self, baseline_out=None, upgraded_out=None):
        """
        Full pipeline: parse JSON, generate ST files, save them, and compile.
        Returns a result dictionary for batch processing.
        """
        result = {
            "json_file"   : self.json_file,
            "baseline_steps"      : 0,
            "baseline_transitions": 0,
            "baseline_variables"  : 0,
            "upgraded_steps"      : 0,
            "upgraded_transitions": 0,
            "upgraded_variables"  : 0,
            "baseline_st_file"    : "",
            "upgraded_st_file"    : "",
            "status"     : "",
            "message"    : "",
            "timestamp"  : datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        }
        
        parse_ok = self.parse()
        if not parse_ok:
            result.update(status="FAILED", message="Parse error")
            return result
        
        result["baseline_steps"]       = len(self.baseline_sfc.get('steps', []))
        result["baseline_transitions"] = len(self.baseline_sfc.get('transitions', []))
        result["baseline_variables"]   = len(self.baseline_sfc.get('variables', []))
        result["upgraded_steps"]       = len(self.upgraded_sfc.get('steps', []))
        result["upgraded_transitions"] = len(self.upgraded_sfc.get('transitions', []))
        result["upgraded_variables"]   = len(self.upgraded_sfc.get('variables', []))
        
        self.generate()
        
        if baseline_out is None:
            base = os.path.splitext(self.json_file)[0]
            baseline_out = base + "_baseline.st"
            upgraded_out = base + "_upgraded.st"
        
        result["baseline_st_file"] = baseline_out
        result["upgraded_st_file"] = upgraded_out
        
        if not self.save(baseline_out, upgraded_out):
            result.update(status="FAILED", message="Save error")
            return result
        
        b_ok, b_msg, u_ok, u_msg = self.compile(baseline_out, upgraded_out)
        
        result["status"] = "SUCCESS" if (b_ok and u_ok) else "FAILED"
        result["message"] = "Baseline: {}\nUpgraded: {}".format(
            "OK" if b_ok else "FAILED - {}".format(b_msg),
            "OK" if u_ok else "FAILED - {}".format(u_msg)
        )
        
        # Console final banner per file
        if not (b_ok and u_ok):
            print("  DETAILS  :\n{}".format(result["message"]))
        
        return result


